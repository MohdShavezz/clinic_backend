import "dotenv/config";
import pg from "pg";

const { Pool } = pg;

export const pool = new Pool({
  ...(process.env.DATABASE_URL
    ? { connectionString: process.env.DATABASE_URL }
    : {
        host: process.env.DB_HOST || "localhost",
        port: Number(process.env.DB_PORT || 5432),
        user: process.env.DB_USER || "postgres",
        password: process.env.DB_PASSWORD,
        database: process.env.DB_NAME,
      }),
  ...(process.env.PG_SSL === "true"
    ? { ssl: { rejectUnauthorized: process.env.PG_SSL_REJECT_UNAUTHORIZED !== "false" } }
    : {}),
  max: Number(process.env.PG_POOL_MAX || 5),
  idleTimeoutMillis: 10000,
  connectionTimeoutMillis: 10000,
});

pool.on("error", (error) => console.error("Unexpected PostgreSQL pool error:", error));

export const dbConn = async () => {
  await pool.query(`
    CREATE TABLE IF NOT EXISTS users (
      id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      fullname TEXT NOT NULL,
      email TEXT NOT NULL UNIQUE,
      phone JSONB NOT NULL DEFAULT '{}'::jsonb,
      password TEXT NOT NULL,
      role TEXT NOT NULL DEFAULT 'user' CHECK (role IN ('user', 'admin')),
      profile JSONB NOT NULL DEFAULT '{}'::jsonb,
      address JSONB NOT NULL DEFAULT '{}'::jsonb,
      email_otp INTEGER,
      phone_otp INTEGER,
      is_email_verified BOOLEAN NOT NULL DEFAULT FALSE,
      is_phone_verified BOOLEAN NOT NULL DEFAULT FALSE,
      liked_items JSONB NOT NULL DEFAULT '[]'::jsonb,
      created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
      updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
    );

    CREATE TABLE IF NOT EXISTS blacklisted_tokens (
      token TEXT PRIMARY KEY,
      created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
      expires_at TIMESTAMPTZ NOT NULL
    );
    CREATE INDEX IF NOT EXISTS blacklisted_tokens_expires_at_idx ON blacklisted_tokens (expires_at);

    CREATE TABLE IF NOT EXISTS patients (
      patient_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      doctor_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
      patient_name TEXT NOT NULL,
      patient_age SMALLINT CHECK (patient_age IS NULL OR patient_age BETWEEN 0 AND 125),
      patient_phone TEXT,
      patient_email TEXT,
      patient_address TEXT,
      patient_city TEXT,
      patient_state TEXT,
      patient_pincode TEXT,
      patient_country TEXT,
      patient_marker TEXT NOT NULL DEFAULT 'Active',
      patient_remark TEXT,
      created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
      updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
      archived_at TIMESTAMPTZ
    );
    ALTER TABLE patients ADD COLUMN IF NOT EXISTS patient_remark TEXT;
    CREATE INDEX IF NOT EXISTS patients_doctor_name_idx ON patients (doctor_id, patient_name);

    CREATE TABLE IF NOT EXISTS labs (
      lab_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      doctor_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
      lab_name TEXT NOT NULL,
      contact_name TEXT,
      phone TEXT,
      email TEXT,
      address TEXT,
      city TEXT,
      state TEXT,
      pincode TEXT,
      country TEXT,
      created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
      updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
      archived_at TIMESTAMPTZ
    );

    CREATE TABLE IF NOT EXISTS report_parameters_master (
      parameter_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      doctor_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
      parameter TEXT NOT NULL,
      unit TEXT NOT NULL DEFAULT '',
      created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
      UNIQUE (doctor_id, parameter)
    );

    CREATE TABLE IF NOT EXISTS medical_tests (
      test_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      doctor_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
      test_name TEXT NOT NULL,
      description TEXT,
      active BOOLEAN NOT NULL DEFAULT TRUE,
      created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
      updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
      archived_at TIMESTAMPTZ
    );
    CREATE UNIQUE INDEX IF NOT EXISTS medical_tests_doctor_name_idx ON medical_tests (doctor_id, LOWER(test_name));

    CREATE TABLE IF NOT EXISTS medical_test_parameters (
      test_id BIGINT NOT NULL REFERENCES medical_tests(test_id) ON DELETE CASCADE,
      parameter_id BIGINT NOT NULL REFERENCES report_parameters_master(parameter_id) ON DELETE RESTRICT,
      unit TEXT NOT NULL DEFAULT '',
      PRIMARY KEY (test_id, parameter_id)
    );

    CREATE TABLE IF NOT EXISTS consultations (
      consultation_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      patient_id BIGINT NOT NULL REFERENCES patients(patient_id) ON DELETE RESTRICT,
      doctor_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
      date_of_consultation DATE NOT NULL DEFAULT CURRENT_DATE,
      scanned_doc_id TEXT,
      next_consultation_date DATE,
      notes TEXT,
      created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
      updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
      CHECK (next_consultation_date IS NULL OR next_consultation_date >= date_of_consultation)
    );
    CREATE INDEX IF NOT EXISTS consultations_patient_date_idx ON consultations (patient_id, date_of_consultation DESC);

    CREATE TABLE IF NOT EXISTS consultation_tests (
      consultation_test_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      consultation_id BIGINT NOT NULL REFERENCES consultations(consultation_id) ON DELETE CASCADE,
      test_id BIGINT NOT NULL REFERENCES medical_tests(test_id) ON DELETE RESTRICT,
      lab_id BIGINT NOT NULL REFERENCES labs(lab_id) ON DELETE RESTRICT,
      status TEXT NOT NULL DEFAULT 'Suggested' CHECK (status IN ('Suggested', 'Scheduled', 'Completed', 'Cancelled')),
      UNIQUE (consultation_id, test_id, lab_id)
    );

    CREATE TABLE IF NOT EXISTS medical_reports (
      report_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      patient_id BIGINT NOT NULL REFERENCES patients(patient_id) ON DELETE RESTRICT,
      consultation_id BIGINT REFERENCES consultations(consultation_id) ON DELETE SET NULL,
      test_id BIGINT REFERENCES medical_tests(test_id) ON DELETE SET NULL,
      lab_id BIGINT NOT NULL REFERENCES labs(lab_id) ON DELETE RESTRICT,
      doctor_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
      date_of_test DATE NOT NULL,
      scanned_doc_id TEXT,
      notes TEXT,
      created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
    );
    CREATE INDEX IF NOT EXISTS medical_reports_patient_date_idx ON medical_reports (patient_id, date_of_test DESC);

    CREATE TABLE IF NOT EXISTS medical_report_parameters (
      report_parameter_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      report_id BIGINT NOT NULL REFERENCES medical_reports(report_id) ON DELETE CASCADE,
      parameter_id BIGINT REFERENCES report_parameters_master(parameter_id) ON DELETE SET NULL,
      parameter TEXT NOT NULL,
      unit TEXT NOT NULL DEFAULT '',
      result_value TEXT NOT NULL,
      reference_range TEXT,
      UNIQUE (report_id, parameter)
    );
  `);
  console.log("PostgreSQL connected and clinic schema is ready");
  return pool;
};
